/* ═══════════════════════════════════════════
   APPLY LANGUAGE
═══════════════════════════════════════════ */
let currentLang = "en";
function applyLang(lang) {
  currentLang = lang;
  const t = translations[lang];
  if (!t) return;

  // Text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // innerHTML for keys with & entities
  ["nav.services", "svc.h2b", "svc.s1h", "svc.s2h", "cta.h2a"].forEach((k) => {
    document.querySelectorAll(`[data-i18n="${k}"]`).forEach((el) => {
      if (t[k]) el.innerHTML = t[k];
    });
  });

  // Direction
  const isRTL = lang === "ar" || lang === "he";
  document.documentElement.setAttribute("dir", isRTL ? "rtl" : "ltr");
  document.documentElement.setAttribute("lang", lang);

  // Active button
  document.querySelectorAll(".lang-btn").forEach((b) => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
}

// Wire up all language buttons (both desktop and mobile)
document.querySelectorAll(".lang-btn").forEach((btn) => {
  btn.addEventListener("click", () => {
    applyLang(btn.dataset.lang);
    // Sync the other switcher
    document.querySelectorAll(".lang-btn").forEach((b) => {
      b.classList.toggle("active", b.dataset.lang === btn.dataset.lang);
    });
  });
});

